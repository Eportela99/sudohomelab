"""vault group: an encrypted secrets store (Fernet / AES) in SQLite.

The key comes from VAULT_KEY (generated by the installer into .env), so the
database file alone is useless if it leaks. vault_list never shows secrets."""
import datetime as dt
import json
import os
import re
import sqlite3
import threading

from common import DATA_DIR, as_int, env

GROUP = "vault"
TOOLS = ["vault_store", "vault_list", "vault_get", "vault_forget"]

VAULT_DB = env("VAULT_DB", os.path.join(DATA_DIR, "vault.db"))
_lock = threading.Lock()
_cipher = None


def _fernet():
    global _cipher
    if _cipher is None:
        from cryptography.fernet import Fernet
        key = env("VAULT_KEY")
        if not key:
            raise RuntimeError("VAULT_KEY is not set; the vault is disabled")
        _cipher = Fernet(key.encode())
    return _cipher


def _db():
    os.makedirs(os.path.dirname(VAULT_DB), exist_ok=True)
    con = sqlite3.connect(VAULT_DB, timeout=30)
    con.execute("CREATE TABLE IF NOT EXISTS vault_items(name TEXT PRIMARY KEY, kind TEXT, "
                "username TEXT, host TEXT, port INTEGER, secret_enc TEXT NOT NULL, notes TEXT, "
                "created_at INTEGER NOT NULL, updated_at INTEGER NOT NULL, last_used_at INTEGER)")
    return con


def _name(name):
    return re.sub(r"[^A-Za-z0-9_.@-]+", "-", (name or "").strip()).strip("-").lower()


def _now():
    return int(dt.datetime.now().timestamp())


def register(mcp):
    @mcp.tool()
    def vault_store(name: str, secret: str, kind: str | None = "secret",
                    username: str | None = None, host: str | None = None,
                    port: int | float | str | None = None, notes: str | None = None) -> str:
        """Store a secret encrypted (password, API token, SSH key, login).
        Storing the same name again replaces it."""
        key = _name(name)
        if not key or not secret:
            return "vault_store: name and secret are required."
        try:
            enc = _fernet().encrypt(secret.encode()).decode()
            with _lock:
                con = _db()
                old = con.execute("SELECT created_at, last_used_at FROM vault_items WHERE name=?",
                                  (key,)).fetchone()
                con.execute("INSERT OR REPLACE INTO vault_items VALUES(?,?,?,?,?,?,?,?,?,?)",
                            (key, (kind or "secret").strip(), (username or "").strip(),
                             (host or "").strip(), as_int(port, None), enc, (notes or "").strip(),
                             old[0] if old else _now(), _now(), old[1] if old else None))
                con.commit()
                con.close()
        except Exception as e:
            return "vault_store error: %s" % e
        return "Stored encrypted %s '%s'." % (kind or "secret", key)

    @mcp.tool()
    def vault_list(limit: int | float | str | None = 100) -> str:
        """List vault entries (names and details only; secrets are never shown)."""
        with _lock:
            con = _db()
            rows = con.execute("SELECT name, kind, username, host, port, notes, updated_at, "
                               "last_used_at FROM vault_items ORDER BY name LIMIT ?",
                               (max(1, min(500, as_int(limit, 100))),)).fetchall()
            con.close()
        if not rows:
            return "The vault is empty."
        out = ["Vault entries (%d):" % len(rows)]
        for name, kind, user, host, port, notes, upd, used in rows:
            loc = (" %s@%s" % (user, host) if user or host else "") + (":%s" % port if port else "")
            out.append("- %s: %s%s (updated %s, last used %s)%s" % (
                name, kind, loc, dt.datetime.fromtimestamp(upd).strftime("%Y-%m-%d"),
                dt.datetime.fromtimestamp(used).strftime("%Y-%m-%d") if used else "never",
                " - " + notes if notes else ""))
        return "\n".join(out)

    @mcp.tool()
    def vault_get(name: str) -> str:
        """Read one secret from the vault. Treat the result as sensitive."""
        key = _name(name)
        with _lock:
            con = _db()
            row = con.execute("SELECT name, kind, username, host, port, secret_enc, notes "
                              "FROM vault_items WHERE name=?", (key,)).fetchone()
            if row:
                con.execute("UPDATE vault_items SET last_used_at=? WHERE name=?", (_now(), key))
                con.commit()
            con.close()
        if not row:
            return "No vault entry named %r." % key
        try:
            secret = _fernet().decrypt(row[5].encode()).decode()
        except Exception as e:
            return "vault_get error: can't decrypt (%s); was VAULT_KEY changed?" % type(e).__name__
        meta = dict(zip(("name", "kind", "username", "host", "port"), row[:5]),
                    notes=row[6], secret=secret)
        return "Vault entry (sensitive):\n```json\n%s\n```" % json.dumps(meta, indent=2)

    @mcp.tool()
    def vault_forget(name: str) -> str:
        """Delete one secret from the vault."""
        key = _name(name)
        with _lock:
            con = _db()
            n = con.execute("DELETE FROM vault_items WHERE name=?", (key,)).rowcount
            con.commit()
            con.close()
        return ("Deleted vault entry '%s'." % key) if n else ("No vault entry named %r." % key)
